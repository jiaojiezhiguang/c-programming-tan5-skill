/* 数列排序
 * 题目：给定长度为 n 的数列，按从小到大排序。1 <= n <= 200，每个整数绝对值 < 10000
 * 知识点范围：第1章 程序结构 + 第3章 输入输出 + 第5章 循环 + 第6章 数组
 *            （不使用第7章函数、第9章结构体、第10章文件）
 * 排序方法：起泡法（教材例6.3）
 */
#include <stdio.h>

#define N 200            /* 题目给定 n <= 200，用符号常量做数组长度 */

int main()
{
    int a[N];            /* 存放待排序的数列 */
    int n;               /* 实际元素个数 */
    int i, j, t;         /* i: 内层下标  j: 趟数  t: 交换用的临时变量 */

    /* ---- 1. 读入数据 ---- */
    scanf("%d", &n);
    for (i = 0; i < n; i++)
        scanf("%d", &a[i]);

    /* ---- 2. 起泡法升序排序 ---- */
    /* 外层 j 控制趟数：n 个数需要 n-1 趟 */
    for (j = 0; j < n - 1; j++)
        /* 内层 i 控制本趟比较次数：第 j 趟只需比较 n-1-j 次
         * （末尾 j 个数已经"沉底"到位，不必再比） */
        for (i = 0; i < n - 1 - j; i++)
            if (a[i] > a[i + 1]) {        /* 前面的比后面的大 → 交换 */
                t = a[i];                 /* 必须借助第三个变量， */
                a[i] = a[i + 1];          /* 直接写 a[i]=a[i+1]; a[i+1]=a[i]; 会丢值 */
                a[i + 1] = t;
            }

    /* ---- 3. 输出结果 ---- */
    /* 题目要求输出一行，数字间用一个空格分隔，末尾不加多余空格 */
    for (i = 0; i < n; i++) {
        if (i > 0)
            printf(" ");
        printf("%d", a[i]);
    }
    printf("\n");

    return 0;
}
